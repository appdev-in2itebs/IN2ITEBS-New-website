// Turns the five hero videos into frame sequences (owner, 2026-09-21): the homepage hero must not
// play a video file; it plays still images one after another, like a flip book, so each clip is
// sampled into WebP frames here and `components/media/frame-sequence.tsx` draws them on a canvas.
//
//   node scripts/extract-hero-frames.mjs
//
// Reads  ../Herosection Video/video1.mp4 … video5.mp4 (1920x1080, 24 fps, 10 s each)
// Writes public/hero-frames/slide-N/w1280/f0001.webp … and w768/…, plus poster.jpg per slide,
//        and content/hero-frames.ts with the counts the player needs.
//
// 12 frames a second is the budget: it keeps motion smooth for slow ambient footage while halving
// what a visitor downloads, and the player times playback from `fps`, so the clip still lasts its
// full ten seconds. Re-run after replacing a video.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import ffmpeg from "ffmpeg-static";

const FPS = 12;
const SETS = [
  { name: "w1280", width: 1280, quality: 72 },
  { name: "w768", width: 768, quality: 68 },
];
// HERO_SOURCE points at another folder of video1.mp4 … video5.mp4 (e.g. the clips with the Gemini
// sparkle removed, 2026-10-06).
const source = path.resolve(process.env.HERO_SOURCE ?? path.join("..", "Herosection Video"));
const out = path.resolve("public", "hero-frames");
const slides = [1, 2, 3, 4, 5];
const manifest = [];

for (const n of slides) {
  const input = path.join(source, `video${n}.mp4`);
  if (!existsSync(input)) throw new Error(`missing ${input}`);
  const slug = `slide-${n}`;
  const dir = path.join(out, slug);
  rmSync(dir, { recursive: true, force: true });
  let frames = 0;
  for (const set of SETS) {
    const setDir = path.join(dir, set.name);
    mkdirSync(setDir, { recursive: true });
    execFileSync(
      ffmpeg,
      [
        "-hide_banner",
        "-loglevel",
        "error",
        "-i",
        input,
        "-vf",
        `fps=${FPS},scale=${set.width}:-2:flags=lanczos`,
        "-c:v",
        "libwebp",
        "-quality",
        String(set.quality),
        "-compression_level",
        "6",
        path.join(setDir, "f%04d.webp"),
      ],
      { stdio: "inherit" },
    );
    const count = readdirSync(setDir).filter((f) => f.endsWith(".webp")).length;
    frames = frames ? Math.min(frames, count) : count;
  }
  // The poster is the first frame, as a JPEG so the pre-hydration markup needs no WebP support.
  execFileSync(
    ffmpeg,
    [
      "-hide_banner",
      "-loglevel",
      "error",
      "-i",
      input,
      "-vframes",
      "1",
      "-vf",
      "scale=1280:-2",
      "-q:v",
      "4",
      path.join(dir, "poster.jpg"),
    ],
    { stdio: "inherit" },
  );
  manifest.push({ slug, frames, fps: FPS, width: 1280, height: 720 });
  console.log(`${slug}: ${frames} frames`);
}

const ts = `/**
 * GENERATED by scripts/extract-hero-frames.mjs — do not edit. The homepage hero's frame sequences:
 * each of the five clips in ../Herosection Video sampled at ${FPS} frames a second into WebP stills
 * under /public/hero-frames/<slug>/<set>/f0001.webp…, with a JPEG poster beside them.
 */
export interface HeroFrameSequence {
  slug: string;
  frames: number;
  fps: number;
  width: number;
  height: number;
}

export const HERO_FRAME_SETS = { wide: "w1280", narrow: "w768" } as const;

export const heroFrames: Record<string, HeroFrameSequence> = ${JSON.stringify(
  Object.fromEntries(manifest.map((m) => [m.slug, m])),
  null,
  2,
)};

export function heroFrameUrl(slug: string, set: string, index: number) {
  return \`/hero-frames/\${slug}/\${set}/f\${String(index + 1).padStart(4, "0")}.webp\`;
}

export function heroPosterUrl(slug: string) {
  return \`/hero-frames/\${slug}/poster.jpg\`;
}
`;
writeFileSync(path.resolve("content", "hero-frames.ts"), ts);
console.log("wrote content/hero-frames.ts");
